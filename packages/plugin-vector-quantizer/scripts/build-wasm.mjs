#!/usr/bin/env node
// Rebuilds the WebAssembly product quantizer and inlines it into src/wasm-binary.ts as base64.
//
// Requirements (only for maintainers; users of the package never need Rust):
//   rustup target add wasm32-unknown-unknown
//
// Usage: node scripts/build-wasm.mjs [--check] [--wasm-opt]
//   --check     fails if the committed src/wasm-binary.ts does not match a fresh build (same rustc version).
//   --wasm-opt  also runs binaryen's wasm-opt -O3 (must be on PATH). Off by default so builds stay reproducible.

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, existsSync, copyFileSync, mkdtempSync, rmSync } from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const crateDir = join(root, 'rust')
const output = join(root, 'src', 'wasm-binary.ts')
const check = process.argv.includes('--check')

// Strip machine-specific paths from the binary so that rebuilds are reproducible across machines.
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), '.cargo')
const rustflags = [`--remap-path-prefix=${crateDir}=/build`, `--remap-path-prefix=${cargoHome}=/cargo`].join(' ')
const rustc = execFileSync('rustc', ['--version'], { encoding: 'utf8' }).trim()

execFileSync(
  'cargo',
  [
    'build',
    '--release',
    '--locked',
    '--target',
    'wasm32-unknown-unknown',
    '--manifest-path',
    join(crateDir, 'Cargo.toml')
  ],
  { stdio: 'inherit', env: { ...process.env, RUSTFLAGS: rustflags } }
)

const built = join(crateDir, 'target', 'wasm32-unknown-unknown', 'release', 'zbsearch_vector_quantizer_wasm.wasm')
const work = mkdtempSync(join(tmpdir(), 'zbsearch-vq-'))
let wasmPath = join(work, 'module.wasm')
copyFileSync(built, wasmPath)

if (process.argv.includes('--wasm-opt')) {
  const optimized = join(work, 'module.opt.wasm')
  execFileSync('wasm-opt', ['-O3', wasmPath, '-o', optimized], { stdio: 'inherit' })
  wasmPath = optimized
}

const bytes = readFileSync(wasmPath)
rmSync(work, { recursive: true, force: true })

const sha256 = createHash('sha256').update(bytes).digest('hex')
const base64 = bytes.toString('base64')
const lines = base64.match(/.{1,100}/g) ?? []

const source = `// This file is generated by scripts/build-wasm.mjs. Do not edit it by hand.
//
// Compiled from ./rust (GPL-3.0-only), which vendors the product quantizer of vector_quantizer 0.0.3
// (https://github.com/oramasearch/vector_quantizer, commit cfdec78a061bd13bc60130dd4c2ced3f64338dcf).
// Built with ${rustc}. Size: ${bytes.length} bytes. SHA-256: ${sha256}

export const WASM_SHA256 = '${sha256}'

export const WASM_BASE64 =
${lines.map((line, index) => `  '${line}'${index === lines.length - 1 ? '' : ' +'}`).join('\n')}
`

if (check) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : ''
  if (current !== source) {
    console.error('src/wasm-binary.ts is out of date. Run `pnpm build:wasm` and commit the result.')
    process.exit(1)
  }
  console.log(`src/wasm-binary.ts is up to date (${bytes.length} bytes, sha256 ${sha256})`)
} else {
  writeFileSync(output, source)
  console.log(`Wrote ${output} (${bytes.length} bytes, sha256 ${sha256})`)
}
